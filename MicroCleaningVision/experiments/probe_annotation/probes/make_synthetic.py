"""Create reproducible, explicitly synthetic PatchCore smoke-test images."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "dataset" / "stage2_synthetic"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _periodic(size: int, seed: int) -> np.ndarray:
    y, x = np.mgrid[:size, :size]
    base = 125 + 35 * np.sin(2 * np.pi * x / 12) + 24 * np.sin(2 * np.pi * y / 17)
    base += 10 * np.sin(2 * np.pi * (x + y) / 29)
    noise = np.random.default_rng(seed).normal(0, 1.5, (size, size))
    gray = np.clip(base + noise, 0, 255).astype(np.uint8)
    return np.repeat(gray[..., None], 3, axis=2)


def make() -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    normal = _periodic(256, 117)
    query = _periodic(280, 118)
    mask = Image.new("L", (280, 280), 0)
    draw = ImageDraw.Draw(mask)
    draw.ellipse((45, 52, 95, 102), fill=255)
    draw.rectangle((175, 170, 224, 212), fill=255)
    draw.polygon([(120, 220), (140, 185), (158, 222)], fill=255)
    clean_query = Image.fromarray(query)
    rgb = Image.fromarray(query)
    draw_rgb = ImageDraw.Draw(rgb)
    draw_rgb.ellipse((45, 52, 95, 102), fill=(18, 15, 12))
    draw_rgb.rectangle((175, 170, 224, 212), fill=(245, 26, 210))
    draw_rgb.polygon([(120, 220), (140, 185), (158, 222)], fill=(20, 220, 245))
    paths = {"normal": OUT / "normal.png", "query_normal": OUT / "query_normal.png",
             "query": OUT / "query_with_spots.png", "mask": OUT / "synthetic_mask.png"}
    if OUT.exists() and any(p.exists() for p in paths.values()):
        raise FileExistsError(f"Refusing to overwrite existing synthetic fixtures in {OUT}")
    Image.fromarray(normal).save(paths["normal"])
    clean_query.save(paths["query_normal"])
    rgb.save(paths["query"])
    mask.save(paths["mask"])
    manifest = {"schema": "patchcore-reference-v1", "synthetic": True,
                "source": "generated by python -m probes.make_synthetic; periodic texture and scripted spots",
                "design_id": "synthetic-periodic-v1", "verified_clean": True,
                "verified_by": "synthetic-generator-selfcheck", "images": [{
                    "raw_image_ref": paths["normal"].relative_to(ROOT).as_posix(),
                    "sha256": _sha(paths["normal"]), "design_id": "synthetic-periodic-v1"}]}
    (OUT / "reference_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return OUT


if __name__ == "__main__":
    print(make())
